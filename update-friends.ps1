# ============================================================================
#  update-friends.ps1
#  Builds js/friends-data.js for friends.html
#  ----------------------------------------------------------------------------
#  Where photos live:
#    img/                     -> "all photos" (wall + carousel)
#    img/friends/<name>/      -> one section per folder; the folder name is
#                                the default section title (override it in
#                                friends.html -> window.FRIEND_NAMES)
#
#  Photo paths in the data file are relative to img/, e.g.
#    "微信图片_1.jpg"                 a photo sitting in img/
#    "friends/岑/微信图片_2.jpg"       a photo inside a group folder
#  friends.html builds every <img src> from these paths, so each photo only
#  has to exist once -- no copies in img/.
#
#  Run it with 更新照片.bat  (works with pwsh or the built-in powershell).
# ============================================================================
$ErrorActionPreference = 'Stop'

$root       = $PSScriptRoot
$img        = Join-Path $root 'img'
$friendsDir = Join-Path $img 'friends'
$dataFile   = Join-Path $root 'js\friends-data.js'

$exts = @('.jpg', '.jpeg', '.png', '.gif', '.webp', '.avif')

function Get-PhotoNames([string]$dir) {
    if (-not (Test-Path -LiteralPath $dir)) { return @() }
    return @(
        Get-ChildItem -LiteralPath $dir -File |
            Where-Object { $exts -contains $_.Extension.ToLower() } |
            Sort-Object Name |
            ForEach-Object { $_.Name }
    )
}

# 1. photos sitting directly in img/  ->  "name.jpg"
$rootPhotos = @(Get-PhotoNames $img)

# 2. one group per folder in img/friends/  ->  "friends/<folder>/name.jpg"
$groups = @()
if (Test-Path -LiteralPath $friendsDir) {
    foreach ($d in (Get-ChildItem -LiteralPath $friendsDir -Directory | Sort-Object Name)) {
        $names = @(Get-PhotoNames $d.FullName)
        if ($names.Count -gt 0) {
            $paths = @($names | ForEach-Object { 'friends/' + $d.Name + '/' + $_ })
            $groups += @{ name = $d.Name; photos = $paths }
        }
    }
}

# 3. "all" = img/ root + every group, ordered by file name
$all = @($rootPhotos)
foreach ($g in $groups) { $all += $g.photos }
$all = @($all | Sort-Object -Unique | Sort-Object { Split-Path $_ -Leaf })

function To-JsonArray($value) {
    if ($null -eq $value -or $value.Count -eq 0) { return '[]' }
    $json = ConvertTo-Json -InputObject @($value) -Compress -Depth 6
    if ($json -notmatch '^\[') { $json = '[' + $json + ']' }
    return $json
}

$allJson    = To-JsonArray $all
$groupsJson = To-JsonArray $groups
$now        = Get-Date -Format 'yyyy-MM-dd HH:mm'

$js = @"
/* =========================================================================
   Photo data for friends.html
   AUTO-GENERATED by update-friends.ps1 -- do not edit this file by hand.
   -------------------------------------------------------------------------
   To update the photos:
     1. Put photos into  img/                    (all photos + carousel)
     2. Put photos into  img/friends/<name>/     (one section per folder)
     3. Double-click     更新照片.bat
     4. Refresh friends.html

   Paths below are relative to img/, e.g. "friends/岑/x.jpg".
   To change a section title WITHOUT renaming the folder, edit
   window.FRIEND_NAMES at the bottom of friends.html.
   Generated: $now
   ========================================================================= */
var FRIENDS_DATA = (function () {
  var all = $allJson;
  var groups = $groupsJson;
  return { updated: '$now', all: all, groups: groups };
})();
"@

$dir = Split-Path $dataFile -Parent
if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }

[System.IO.File]::WriteAllText($dataFile, $js, (New-Object System.Text.UTF8Encoding($false)))

Write-Host ''
Write-Host ('OK  {0} photo(s) in total, {1} group(s)' -f $all.Count, $groups.Count)
if ($groups.Count -gt 0) {
    foreach ($g in $groups) { Write-Host ('    - {0}  ({1})' -f $g.name, $g.photos.Count) }
}
Write-Host ('Data written to {0}' -f $dataFile)
